// Package tc18gap enumerates, as machine-readable data, every OPEN Alliance
// TC18 normative clause that go-RCP's requirements corpus records as NOT
// IMPLEMENTED.
//
// # Why this package exists
//
// .fusa-reqs.json is meant to be a complete and honest map of TC18's
// normative surface: a MUST/SHALL clause, a mandatory table, or a figure
// defining a wire layout gets a requirement entry whether or not this module
// implements it. An entry the module does not satisfy carries
// status "not-implemented" and a text beginning "NOT IMPLEMENTED — ".
//
// Those entries still have to be traceable, and a claim of "we know this is
// missing" is only worth anything if something checks that the claim is still
// accurate. This package is that something. Each Gap below is the code-side
// anchor for one such requirement; the package's tests assert that the
// registry and .fusa-reqs.json agree exactly, in both directions, so a
// requirement cannot be quietly retitled, re-scoped, deleted, or flipped to
// "implemented" without the mismatch failing the build.
//
// It is also directly useful to a consumer: Gaps() is the answer to "which
// parts of TC18 does this library not do?", in a form a conformance harness or
// an integrator's gap analysis can consume, rather than prose scattered across
// a dozen doc.go files.
//
// # What a Gap is not
//
// A Gap is not a defect report and not a roadmap commitment. Many entries are
// clauses TC18 itself marks optional, several are clauses whose specification
// text is internally inconsistent (the Section citation records where), and
// some describe behaviour this module deliberately does not offer. The
// requirement entry's own text carries that reasoning; this registry carries
// only the identity and the citation.
package tc18gap

// Gap is one TC18 normative clause that go-RCP does not implement.
type Gap struct {
	// ReqID is the .fusa-reqs.json requirement identifier, e.g. "REQ-TC18-001".
	ReqID string
	// Section cites the governing TC18 clause, table or figure, together with
	// the line number(s) in the specification text the citation was read from.
	Section string
	// Title repeats the requirement's one-line title, so a caller listing gaps
	// does not have to parse .fusa-reqs.json to render something readable.
	Title string
}

// Gaps returns every recorded gap, in requirement-identifier order. The
// returned slice is a copy: mutating it does not affect the registry.
func Gaps() []Gap {
	out := make([]Gap, len(gaps))
	copy(out, gaps)
	return out
}

// Lookup returns the gap recorded for reqID, if any. A false second result
// means the requirement is either implemented or unknown — callers wanting to
// distinguish those two cases must consult .fusa-reqs.json itself.
func Lookup(reqID string) (Gap, bool) {
	for _, g := range gaps {
		if g.ReqID == reqID {
			return g, true
		}
	}
	return Gap{}, false
}

